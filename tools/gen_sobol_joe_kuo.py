"""Writes include/mootation/sobol_joe_kuo.hpp: dimensions 101 ... 21 201 of Joe
and Kuo's direction numbers (python/mootation/_sobol/new-joe-kuo-6.21201),
for sobol.hpp beyond its own table of dimensions 2 ... 100 (task 24, §24.3.2).

    python tools/gen_sobol_joe_kuo.py           # writes the header
    python tools/gen_sobol_joe_kuo.py --check   # exit 1 if the header is not what the file gives

Each dimension is the file's line without its first number d, "s a m_1 ...
m_s", as a string literal: the header reads as the file does, and a compiler
parses string literals much faster than an array of 350 000 integers."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "python" / "mootation" / "_sobol" / "new-joe-kuo-6.21201"
LICENCE = ROOT / "python" / "mootation" / "_sobol" / "LICENSE.txt"
HEADER = ROOT / "include" / "mootation" / "sobol_joe_kuo.hpp"
FIRST = 101                       # sobol.hpp's own table holds dimensions 2 ... 100


def text() -> str:
    lines = SOURCE.read_text(encoding="ascii").split("\n")
    rows = []
    for k, line in enumerate(lines[1:], start=2):        # line 1 is the heading "d s a m_i"
        f = line.split()
        if not f:
            continue
        if int(f[0]) != k:
            raise SystemExit(f"{SOURCE.name}: line {k}: dimension {f[0]}, not {k}")
        if k >= FIRST:
            rows.append(" ".join(f[1:]))
    last = FIRST + len(rows) - 1
    licence = [("// " + l).rstrip() for l in LICENCE.read_text(encoding="ascii").rstrip("\n").split("\n")]
    out = ["#pragma once",
           "// SPDX-License-Identifier: Apache-2.0 (this file's code); the direction",
           "// numbers below are Joe & Kuo's, under their licence, reproduced here:",
           "//"] + licence + [
           "//",
           "// ============================================================================",
           f"// Generated by tools/gen_sobol_joe_kuo.py from {SOURCE.name} (python/",
           "// mootation/_sobol/); do not edit. Dimensions "
           f"{FIRST} ... {last} of the Sobol sequence",
           "// (sobol.hpp holds 1 ... 100), one string each: the file's line without its",
           "// dimension, \"s a m_1 ... m_s\" (degree, polynomial, initial direction numbers).",
           "// ============================================================================",
           "",
           "namespace mootation::sobol::detail {",
           "",
           f"constexpr int kJoeKuoFirst = {FIRST}, kJoeKuoLast = {last};",
           "",
           "// the line of dimension kJoeKuoFirst + i",
           "inline const char* joe_kuo_line(int i)",
           "{",
           "    static const char* const lines[] = {"]
    out += [f'        "{r}",' for r in rows]
    out += ["    };",
            "    return lines[i];",
            "}",
            "",
            "}   // namespace mootation::sobol::detail",
            ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    want = text()
    if args.check:
        have = HEADER.read_text(encoding="ascii") if HEADER.is_file() else ""
        if have != want:
            print(f"{HEADER.relative_to(ROOT)}: not what {SOURCE.name} gives (python tools/gen_sobol_joe_kuo.py)")
            return 1
        print(f"{HEADER.relative_to(ROOT)}: up to date")
        return 0
    HEADER.write_bytes(want.encode("ascii"))
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
