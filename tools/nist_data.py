"""NIST's 27 StRD nonlinear regression files inside the library.

    python tools/nist_data.py           # writes include/mootation/suite/nist_data.hpp
    python tools/nist_data.py --check   # exit 1 if the header is not what the files give

The files are tests/data/nist-strd-nls/<name>.dat, NIST's bytes (its README
has the source and each file's sha256). The header holds each file as a C++
string, one literal per line of the file with its line end written out
("\\r\\n"), so that the bytes are the file's whatever the checkout does to
the source's line ends; tests/test_suite_nist.cpp checks them against the
files. The engine reads the registry's NIST problems from it
(suite/nist.hpp, embedded) and needs no data directory.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data" / "nist-strd-nls"
HEADER = ROOT / "include" / "mootation" / "suite" / "nist_data.hpp"
# suite/nist.hpp's kNames, in its order
NAMES = ("Misra1a", "Chwirut2", "Chwirut1", "Lanczos3", "Gauss1", "Gauss2", "DanWood", "Misra1b",
         "Kirby2", "Hahn1", "Nelson", "MGH17", "Lanczos1", "Lanczos2", "Gauss3", "Misra1c", "Misra1d",
         "Roszman1", "ENSO", "MGH09", "Thurber", "BoxBOD", "Rat42", "MGH10", "Eckerle4", "Rat43", "Bennett5")


def _literal(line: bytes) -> str:
    out = []
    for b in line:
        c = chr(b)
        if c == "\\" or c == '"' or c == "?":         # "?": no trigraph ("19??)")
            out.append("\\" + c)
        elif c == "\r":
            out.append("\\r")
        elif c == "\n":
            out.append("\\n")
        elif 32 <= b < 127:
            out.append(c)
        else:
            raise ValueError(f"a byte the files do not have: {b}")
    return '"' + "".join(out) + '"'


def text() -> str:
    head = [
        "#pragma once",
        "// SPDX-License-Identifier: Apache-2.0",
        "// ============================================================================",
        "// GENERATED by tools/nist_data.py from tests/data/nist-strd-nls/*.dat: do not",
        "// edit.",
        "//",
        "// NIST Standard Reference Data (SRD 140); © U.S. Secretary of Commerce on",
        "// behalf of the United States of America.",
        "//",
        "// The 27 nonlinear regression files of NIST's Statistical Reference Datasets",
        "// as NIST serves them (https://itl.nist.gov/div898/strd/nls/nls_main.shtml;",
        "// the README beside the files has the download and each file's sha256): each",
        "// file one string, its lines with their line ends (CRLF) as they are.",
        "// ============================================================================",
        "",
        "#include <stdexcept>",
        "#include <string>",
        "",
        "namespace mootation::suite::nist {",
        "",
        "// The file <name>.dat, byte for byte.",
        "inline const char* embedded_file(const std::string& name)",
        "{",
    ]
    body = []
    for name in NAMES:
        lines = (DATA / f"{name}.dat").read_bytes().splitlines(keepends=True)
        body.append(f'    if (name == "{name}")')
        body.append("        return " + _literal(lines[0]))
        for line in lines[1:]:
            body.append("               " + _literal(line))
        body[-1] += ";"
    tail = [
        '    throw std::invalid_argument("nist: no file " + name);',
        "}",
        "",
        "}   // namespace mootation::suite::nist",
        "",
    ]
    return "\n".join(head + body + tail)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    want = text()
    if a.check:
        have = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if have != want:
            print(f"{HEADER.relative_to(ROOT)}: not what the files give; run python tools/nist_data.py")
            return 1
        print(f"{HEADER.relative_to(ROOT)}: up to date")
        return 0
    HEADER.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
