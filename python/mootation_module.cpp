// ── The problem, as configured from Python ─────────────────────────────────
// What _core.Problem holds; run() below hands it to mootation::runner::run
// (include/mootation/run_core.hpp) as a RunProblem whose lock is the GIL.
struct PyProblem {
    std::vector<std::pair<double, double>> bounds;
    int    n_objectives = 2;
    int    n_limits     = 0;
    // Binary variables after the real ones (task 7, supplement 2, §3): the
    // evaluators receive the real values, then the bits as 0.0 and 1.0.
    int    n_bin        = 0;
    // A noisy measurement (task 17, supplement 2, §1.3): problem.hpp's
    // is_stochastic(); the cores' caches are off by default where it is set.
    bool   stochastic   = false;
    // One of the two. evaluate_batch is preferred: it crosses the GIL once per
    // generation instead of once per individual.
    std::function<std::vector<double>(std::vector<double>)>               evaluate;
    std::function<std::vector<std::vector<double>>(
        std::vector<std::vector<double>>)>                                evaluate_batch;
    // Optional; must return one row of limits per individual, same convention
    // as the C++ side: <= 0 satisfied, > 0 is the violation.
    std::function<std::vector<std::vector<double>>(
        std::vector<std::vector<double>>)>                                limits_batch;
    // A problem of the C++ suite (include/mootation/suite; task 11 of
    // 2026-10-18, §1.3). Set, the run evaluates it in C++, with the GIL
    // released, and calls none of the three above; bounds, n_objectives and
    // n_limits must be its sizes. The rows it evaluates go to on_rows(X, F,
    // G), arrays of the rows in the order evaluated, a batch at a time: before
    // every on_generation call, at the end of the run and every
    // kNativeRowsCap rows in between. Without on_rows nothing is kept.
    std::shared_ptr<mootation::suite::Native>                             native;
    std::function<void(py::array_t<double>, py::array_t<double>,
                       py::array_t<double>)>                              on_rows;
};

py::array_t<double> rows_array(const std::vector<double>& v, std::size_t n, int width)
{
    py::array_t<double> a({static_cast<py::ssize_t>(n), static_cast<py::ssize_t>(width)});
    std::copy(v.begin(), v.end(), a.mutable_data());
    return a;
}

PyResult run(const std::string& name, PyProblem& problem, const RunConfig& cfg)
{
    mrun::RunProblem p;
    p.bounds = problem.bounds;
    p.n_objectives = problem.n_objectives;
    p.n_limits = problem.n_limits;
    p.n_bin = problem.n_bin;
    p.stochastic = problem.stochastic;
    p.evaluate = problem.evaluate;
    p.evaluate_batch = problem.evaluate_batch;
    p.limits_batch = problem.limits_batch;
    p.native = problem.native;
    if (problem.on_rows) {
        // called with the GIL held (run_core.hpp takes it before every flush)
        p.on_rows = [&problem](const std::vector<double>& X, const std::vector<double>& F,
                               const std::vector<double>& G, std::size_t n) {
            const auto& s = *problem.native;
            problem.on_rows(rows_array(X, n, s.n_var), rows_array(F, n, s.n_obj),
                            rows_array(G, n, s.n_con));
        };
    }
    p.hold = [] { return std::shared_ptr<void>(std::make_shared<py::gil_scoped_acquire>()); };
    p.release = [] { return std::shared_ptr<void>(std::make_shared<py::gil_scoped_release>()); };
    return mrun::run(name, p, cfg);
}

