// ── The problem, as configured from Python ─────────────────────────────────
struct PyProblem {
    std::vector<std::pair<double, double>> bounds;
    int    n_objectives = 2;
    int    n_limits     = 0;
    // Binary variables after the real ones (task 7, supplement 2, §3): the
    // evaluators receive the real values, then the bits as 0.0 and 1.0.
    int    n_bin        = 0;
    // One of the two. evaluate_batch is preferred: it crosses the GIL once per
    // generation instead of once per individual.
    std::function<std::vector<double>(std::vector<double>)>               evaluate;
    std::function<std::vector<std::vector<double>>(
        std::vector<std::vector<double>>)>                                evaluate_batch;
    // Optional; must return one row of limits per individual, same convention
    // as the C++ side: <= 0 satisfied, > 0 is the violation.
    std::function<std::vector<std::vector<double>>(
        std::vector<std::vector<double>>)>                                limits_batch;
    // A problem of the C++ suite (include/mootation/suite; task 11 of
    // 2026-10-18, §1.3). Set, the run evaluates it here, with the GIL
    // released, and calls none of the three above; bounds, n_objectives and
    // n_limits must be its sizes. The rows it evaluates go to on_rows(X, F,
    // G), arrays of the rows in the order evaluated, a batch at a time: before
    // every on_generation call, at the end of the run and every
    // kNativeRowsCap rows in between. Without on_rows nothing is kept.
    std::shared_ptr<mootation::suite::Native>                             native;
    std::function<void(py::array_t<double>, py::array_t<double>,
                       py::array_t<double>)>                              on_rows;
};

// The active problem for the current run. A raw pointer is enough because a run
// is single-threaded from Python's side and the pointer outlives the vault.
PyProblem* g_problem = nullptr;

// Evaluations spent by the current run, counted where the Python evaluator is
// actually called: one per individual through eval_into, the batch size through
// py_run_batch. A warm start plants objectives without evaluating and costs
// nothing. Atomic because the step loop reads it with the GIL released.
std::atomic<long long> g_evaluations{0};

// The wall time the current run spends in the Python evaluators, and how many
// times it calls them: from before the GIL is taken to after the answer is
// copied back, so the crossing and the list conversions are inside, the
// on_generation observer is not. Result.callback_seconds and .callbacks;
// tools/perf takes the crossing as this time minus the time Python measures
// inside the evaluator. Touched only by the thread that runs the core.
double    g_callback_seconds = 0.0;
long long g_callbacks        = 0;

struct CallbackClock {
    std::chrono::steady_clock::time_point start = std::chrono::steady_clock::now();
    ~CallbackClock()
    {
        g_callback_seconds +=
            std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        ++g_callbacks;
    }
};

// The wall time the current run spends evaluating a problem of the suite
// (PyProblem::native): Result.native_seconds, the evaluation's share of a
// run that never calls Python for it.
double g_native_seconds = 0.0;

// The rows a run of a suite problem has evaluated and not yet handed to
// on_rows: variables, objectives and constraint values, row after row.
struct NativeRows {
    std::vector<double> X, F, G;
    std::size_t         n = 0;
};
NativeRows g_rows;
constexpr std::size_t kNativeRowsCap = 4096;

py::array_t<double> rows_array(std::vector<double>& v, std::size_t n, int width)
{
    py::array_t<double> a({static_cast<py::ssize_t>(n), static_cast<py::ssize_t>(width)});
    std::copy(v.begin(), v.end(), a.mutable_data());
    v.clear();
    return a;
}

// Hand the rows kept to on_rows; the caller holds the GIL.
void flush_native_rows()
{
    if (!g_problem || !g_problem->on_rows || g_rows.n == 0) return;
    CallbackClock clock;
    const auto& p = *g_problem->native;
    const std::size_t n = g_rows.n;
    g_rows.n = 0;
    auto X = rows_array(g_rows.X, n, p.n_var);
    auto F = rows_array(g_rows.F, n, p.n_obj);
    auto G = rows_array(g_rows.G, n, p.n_con);
    g_problem->on_rows(std::move(X), std::move(F), std::move(G));
}

void keep_native_row(const std::vector<double>& x, const std::vector<double>& f,
                     const std::vector<double>& g)
{
    if (!g_problem->on_rows) return;
    g_rows.X.insert(g_rows.X.end(), x.begin(), x.end());
    g_rows.F.insert(g_rows.F.end(), f.begin(), f.end());
    g_rows.G.insert(g_rows.G.end(), g.begin(), g.end());
    if (++g_rows.n >= kNativeRowsCap) {
        py::gil_scoped_acquire gil;
        flush_native_rows();
    }
}

// Integer and discrete variables of a suite problem (task 13 of 2026-10-19,
// §3b; RunConfig::var_kinds): the core's genome decoded before the problem
// sees it, as minimize's Python path decodes it (var_types.Layout.decode_one)
// — an integer to the nearest, ties to even, kept in [ceil lo, floor hi]; a
// discrete value to the nearest of its values, ties to the lower — whether
// or not the vault has already rounded the genome (int_repair). The decoded
// row is the one on_rows receives, as the Python path's evaluator receives
// it; the core keeps its genome. Binary and categorical variables are not
// decoded here: minimize.direct_path leaves them to the Python path.
struct NativeDecode {
    std::vector<int>                 kinds;     // per variable: 0 real, 1 integer, 2 discrete; empty: none
    std::vector<std::vector<double>> values;    // a discrete variable's values, sorted
    std::vector<double>              lo, hi;    // an integer's ceil lo and floor hi
    std::vector<double>              x;         // the point decoded
};
NativeDecode g_decode;

// The point the suite problem is evaluated at: vars, or vars decoded.
const std::vector<double>& native_point(const std::vector<double>& vars)
{
    if (g_decode.kinds.empty()) return vars;
    std::vector<double>& x = g_decode.x;
    x = vars;
    for (std::size_t j = 0; j < x.size() && j < g_decode.kinds.size(); ++j) {
        if (g_decode.kinds[j] == 1) {
            // + 0.0: a -0 rounded from (-0.5, 0) is Python's int 0, i.e. +0
            x[j] = std::clamp(std::nearbyint(x[j]), g_decode.lo[j], g_decode.hi[j]) + 0.0;
        } else if (g_decode.kinds[j] == 2 && !g_decode.values[j].empty()) {
            const auto& v = g_decode.values[j];
            auto it = std::lower_bound(v.begin(), v.end(), x[j]);
            if (it == v.end()) x[j] = v.back();
            else if (it == v.begin()) x[j] = v.front();
            else x[j] = (x[j] - *(it - 1) <= *it - x[j]) ? *(it - 1) : *it;
        }
    }
    return x;
}

// One point of a suite problem, evaluated here without the GIL.
void native_eval(const std::vector<double>& vars, std::vector<double>& objs,
                 std::vector<double>& lims)
{
    const auto& p = *g_problem->native;
    objs.assign(static_cast<std::size_t>(p.n_obj), 0.0);
    lims.assign(static_cast<std::size_t>(p.n_con), 0.0);
    const auto start = std::chrono::steady_clock::now();
    p.evaluate(vars.data(), objs.data(), lims.empty() ? nullptr : lims.data());
    g_native_seconds +=
        std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
}

// ── Operator statistics (the 2026-09-23 task, A2/B4/D2) ─────────────────────
// Asked for with RunConfig::operator_stats; nothing below runs otherwise, and
// nothing below draws a random number or evaluates anything, so a run's
// result is the same with or without it (tests/compat_dump.cpp, and
// test_run_layer's operator-statistics test compares the two).
//
// Per step: the population before it (the "parents"), every point the step
// evaluated (the "offspring") and the population after it. The library does
// not track which individuals an offspring came from across its cores, so
// the relations are to the parent POPULATION:
//   survival    an offspring is in the next population. By value: the next
//               population holds more copies of its variable vector than the
//               parents did (a clone of a surviving parent is not counted, a
//               child copied into several MOEA/D neighbours counts once);
//   nd          no parent dominates the offspring (objectives only);
//   step        distance to the nearest parent in variables, over the box
//               diagonal ||ub - lb||.
// The out-of-box counts come from the repair sites (operators/bound_repair.hpp).
struct OpStats {
    bool on = false;
    std::vector<std::vector<double>> log_x, log_f;           // this step's evaluations
    std::vector<std::vector<double>> par_x, par_f;           // the population before it
    // running sums: since the last operator_stats() read, and for the run
    long long off = 0, surv = 0, nd = 0, step_n = 0;
    double    step = 0.0;
    long long t_off = 0, t_surv = 0, t_nd = 0, t_step_n = 0;
    double    t_step = 0.0;
    long long evals_read = 0;
    long long setup_evals = 0;                                // not offspring
    mootation::ops::RepairCounts rc_read;
};
OpStats g_ops;

